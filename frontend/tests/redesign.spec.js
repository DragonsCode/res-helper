    test.setTimeout(300000)
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.setViewportSize(viewport)
    await page.goto('/')
    await expect(page.getByRole('heading', { name: /За каждым выводом/ })).toBeVisible()
