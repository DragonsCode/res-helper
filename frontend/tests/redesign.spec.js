import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function demo(page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Открыть демо' }).click()
  await expect(page.getByRole('heading', { name: 'Рабочий журнал.' })).toBeVisible()
}
async function noOverflow(page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function accessible(page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(result.violations.map(v => ({ id: v.id, impact: v.impact, nodes: v.nodes.map(n => n.target) }))).toEqual([])
}

test('research document: delayed save, failed request, retry, persistence and export', async ({ page }) => {
  await demo(page)
  await page.locator('.project-card').first().click()
  await page.getByRole('button', { name: 'Заполнить паспорт' }).click()
  await page.getByLabel('Исследовательский вопрос', { exact: true }).fill('Меняется ли число наблюдаемых видов в зависимости от времени суток?')
  await page.getByLabel('Метод и протокол', { exact: true }).fill('Одинаковый маршрут, 20 минут наблюдений, две временные точки.')
  await page.getByLabel('Ограничения', { exact: true }).fill('Одна площадка. Причинные выводы невозможны.')
  await page.getByLabel('Предварительные выводы', { exact: true }).fill('Данные ещё не собраны.')
  let release
  const gate = new Promise(resolve => { release = resolve })
  await page.route('**/projects/*/protocol', async route => { await gate; await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Временная ошибка сервера' }) }) })
  await page.getByRole('button', { name: 'Сохранить паспорт' }).click()
  await expect(page.getByRole('button', { name: 'Сохранить паспорт' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Сохранить паспорт' })).toHaveAttribute('aria-busy', 'true')
  release()
  await expect(page.getByRole('alert')).toContainText('Временная ошибка сервера')
  await expect(page.getByLabel('Метод и протокол', { exact: true })).toHaveValue('Одинаковый маршрут, 20 минут наблюдений, две временные точки.')
  await page.screenshot({ path: 'test-results/protocol-error.png', fullPage: true })
  await page.unroute('**/projects/*/protocol')
  await page.getByRole('button', { name: 'Сохранить паспорт' }).click()
  await expect(page.getByRole('status')).toContainText('Паспорт исследования сохранён')
  await page.reload()
  await expect(page.locator('.protocol-document')).toContainText('Причинные выводы невозможны.')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '.md', exact: true }).click()
  expect((await download).suggestedFilename()).toMatch(/^research-protocol-.*\.md$/)
  await accessible(page)
})

test('evidence matrix opens actual linked records, inspector focus and motion', async ({ page }) => {
  await demo(page)
  const cell = page.locator('.matrix-cell').first()
  await cell.focus()
  await page.keyboard.press('Enter')
  let dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  const count = await dialog.locator('.related-item').count()
  expect(count).toBe(Number(await cell.innerText()))
  const title = await dialog.locator('.related-item strong').first().innerText()
  await dialog.locator('.related-item').first().click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(dialog.locator('.source-metadata')).toContainText('Автор / организация')
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => document.querySelector('dialog').contains(document.activeElement))).toBe(true)
  await accessible(page)
  const panelBounds = await dialog.boundingBox()
  await page.mouse.click(panelBounds.x + 10, panelBounds.y + panelBounds.height - 10)
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const search = page.getByRole('button', { name: /Поиск в пространстве/ })
  await search.focus()
  await page.keyboard.press('Control+k')
  await expect(page.getByLabel('Поисковый запрос')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(search).toBeFocused()
  const button = page.getByRole('button', { name: 'Новый проект', exact: true })
  const before = await button.evaluate(e => getComputedStyle(e).backgroundColor)
  await button.hover()
  await expect.poll(() => button.evaluate(e => getComputedStyle(e).backgroundColor)).not.toBe(before)
  await page.mouse.down()
  expect(await button.evaluate(e => getComputedStyle(e).transform)).not.toBe('none')
  await page.mouse.up()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.getByRole('dialog').evaluate(e => getComputedStyle(e).animationName)).toBe('dialog-enter')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await button.click()
  expect(await page.getByRole('dialog').evaluate(e => getComputedStyle(e).animationName)).toBe('none')
  expect(await page.getByRole('dialog').evaluate(e => getComputedStyle(e, '::backdrop').animationName)).toBe('none')
  await page.mouse.click(5, 5)
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('workspace and editorial network errors can be retried; blank search is honest', async ({ page }) => {
  await demo(page)
  await page.route('**/workspaces/*/resources', route => route.abort())
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить пространство' })).toBeVisible()
  await page.unroute('**/workspaces/*/resources')
  await page.getByRole('button', { name: 'Повторить', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Рабочий журнал.' })).toBeVisible()
  await page.goto('/library')
  await page.getByLabel('Поиск по библиотеке').fill('нет-такого-источника')
  await expect(page.getByRole('heading', { name: 'Материалы не найдены' })).toBeVisible()
  await page.getByLabel('Поиск по библиотеке').clear()
  await expect(page.locator('.resource-row')).toHaveCount(6)
  await page.route('**/catalog/reproducible-research', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"Повторите позже"}' }))
  await page.goto('/discover/reproducible-research')
  await expect(page.getByRole('heading', { name: 'Не удалось открыть материал' })).toBeVisible()
  await page.unroute('**/catalog/reproducible-research')
  await page.getByRole('button', { name: 'Повторить', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Эксперимент, который можно повторить', exact: true })).toBeVisible()
})

