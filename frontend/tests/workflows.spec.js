import { test, expect } from '@playwright/test'

async function demo(page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Открыть демо' }).click()
  await expect(page.getByRole('heading', { name: 'Рабочий журнал.' })).toBeVisible()
}

test('public science reading does not require an account', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /За каждым выводом/ })).toBeVisible()
  await page.screenshot({ path: 'test-results/workflow-landing-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'Почитать без регистрации' }).click()
  await expect(page.getByRole('heading', { name: 'Методы и разборы' })).toBeVisible()
  await page.getByRole('link', { name: /Пять вопросов к научной новости/ }).click()
  await expect(page.getByRole('heading', { name: 'Найдите первоисточник' })).toBeVisible()
  await expect(page.getByRole('link', { name: /Open Science Collaboration/ })).toHaveAttribute('href', 'https://doi.org/10.1126/science.aac4716')
  await page.getByRole('link', { name: 'Сохранить свой прогресс' }).click()
  await expect(page.getByRole('heading', { name: 'Начните свой путь в науке' })).toBeVisible()
})

test('research workspace: projects, tasks, materials and discussion persist', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await demo(page)
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Новый проект', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название', { exact: true }).fill('E2E: городская экология')
  await dialog.getByLabel('Направление', { exact: true }).fill('Экология')
  await dialog.getByLabel('Описание', { exact: true }).fill('Сравнение двух городских парков')
  await dialog.getByRole('button', { name: 'Создать проект', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'E2E: городская экология', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Задача', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Что нужно сделать?').fill('Проверить протокол наблюдений')
  await dialog.getByRole('button', { name: 'Добавить', exact: true }).click()
  await page.getByRole('button', { name: 'Завершить: Проверить протокол наблюдений' }).click()
  await expect(page.getByRole('button', { name: 'Возобновить: Проверить протокол наблюдений' })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Возобновить: Проверить протокол наблюдений' })).toBeVisible()
  await page.getByRole('link', { name: 'Источники', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить материал', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название', { exact: true }).fill('Полевой журнал E2E')
  await dialog.getByLabel('Тип', { exact: true }).selectOption('note')
  await dialog.getByLabel('Заметки', { exact: true }).fill('Фиксировать условия и время наблюдений.')
  await dialog.getByRole('button', { name: 'Добавить', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить в избранное: Полевой журнал E2E' }).click()
  await page.getByRole('button', { name: 'Избранное', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Полевой журнал E2E' })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'BibTeX' }).click()
  expect((await download).suggestedFilename()).toBe('research-library.bib')
  await page.getByRole('link', { name: 'Обсуждения', exact: true }).click()
  await page.getByRole('button', { name: 'Начать обсуждение' }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Тема', { exact: true }).fill('Как сравнить две выборки?')
  await dialog.getByLabel('Ваша мысль').fill('Предлагаю сначала проверить метод сбора данных.')
  await dialog.getByRole('button', { name: 'Опубликовать' }).click()
  await expect(page.getByRole('heading', { name: 'Как сравнить две выборки?' })).toBeVisible()
  await page.getByLabel('Ваш ответ').fill('Нужно одинаковое время наблюдения.')
  await page.getByRole('button', { name: 'Отправить ответ' }).click()
  await expect(page.getByText('Нужно одинаковое время наблюдения.', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

